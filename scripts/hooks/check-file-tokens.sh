#!/usr/bin/env bash
#
# Git pre-commit hook: prevents files over 5,000 tokens (tokens = bytes / 4).
# Only checks staged files (excluding deletions).
# Ignores files not authored by agents (lockfiles, codegen, minified bundles, binary assets).
#
set -euo pipefail

MAX_TOKENS=5000
BYTES_PER_TOKEN=4
MAX_BYTES=$((MAX_TOKENS * BYTES_PER_TOKEN)) # 20,000 bytes

# Colors for terminal output
RED='\033[0;31m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

if [ ! -t 1 ]; then
    RED=''
    YELLOW=''
    BLUE=''
    CYAN=''
    BOLD=''
    NC=''
fi

# Function to determine if a file is not authored by agents
is_ignored_file() {
    local file="$1"
    local filename
    filename=$(basename "$file")

    # 1. Custom .tokenignore support at repo root
    if [ -f ".tokenignore" ]; then
        if git check-ignore -q --no-index "$file" 2>/dev/null; then
            return 0
        fi
        while IFS= read -r pattern || [ -n "$pattern" ]; do
            [[ "$pattern" =~ ^[[:space:]]*# ]] && continue
            [[ -z "${pattern// }" ]] && continue
            # shellcheck disable=SC2053
            if [[ "$file" == $pattern || "$filename" == $pattern ]]; then
                return 0
            fi
        done < ".tokenignore"
    fi

    # 2. Package manager lockfiles & wrapper artifacts
    case "$filename" in
        gradle-wrapper.jar|gradlew|gradlew.bat) return 0 ;;
        package-lock.json|npm-shrinkwrap.json|yarn.lock|pnpm-lock.yaml|bun.lockb) return 0 ;;
        uv.lock|poetry.lock|Pipfile.lock|requirements*.txt.lock) return 0 ;;
        Cargo.lock|composer.lock|Gemfile.lock|go.sum|flake.lock) return 0 ;;
        mix.lock|pubspec.lock|Podfile.lock|Package.resolved|packages.lock.json) return 0 ;;
    esac

    # 3. Minified assets, bundles, source maps, compiled binaries
    case "$filename" in
        *.min.js|*.min.css|*.map|*.bundle.js|*.bundle.css) return 0 ;;
        *.wasm|*.pyc|*.pyo|*.class|*.dex|*.o|*.obj|*.dll|*.dylib|*.so|*.exe) return 0 ;;
    esac

    # 4. Media, fonts, images, documents, archives, keystores (binary assets)
    case "${filename,,}" in
        *.png|*.jpg|*.jpeg|*.gif|*.svg|*.webp|*.ico|*.bmp|*.tiff|*.avif) return 0 ;;
        *.woff|*.woff2|*.ttf|*.eot|*.otf) return 0 ;;
        *.mp4|*.webm|*.mov|*.avi|*.mkv|*.mp3|*.wav|*.flac|*.ogg) return 0 ;;
        *.pdf|*.zip|*.tar|*.gz|*.tgz|*.bz2|*.xz|*.7z|*.rar) return 0 ;;
        *.jks|*.keystore|*.p12|*.pem|*.crt|*.aar|*.apk|*.aab|*.jar) return 0 ;;
    esac

    # 5. Build outputs, generated sources, and schemas
    case "$file" in
        build/*|*/build/*|.gradle/*|*/.gradle/*|dist/*|out/*|.next/*|vendor/*|node_modules/*) return 0 ;;
        */generated/*|generated/*|*/schemas/*|schemas/*) return 0 ;;
        *BuildConfig.java|*R.java|*R.class|*R.txt) return 0 ;;
        backend/migrations/versions/*|*alembic/versions/*|*/migrations/*|*/prisma/migrations/*) return 0 ;;
        *.pb.go|*_pb2.py|*_pb2_grpc.py|*.pb.cc|*.pb.h) return 0 ;;
        *.snap|*/__snapshots__/*) return 0 ;;
        *swagger*.json|*openapi*.json|*graphql.schema.json) return 0 ;;
    esac

    # 6. In-file codegen annotations in the first 40 lines of staged content
    local header
    header=$(git show ":$file" 2>/dev/null | head -n 40 || true)
    if [[ "$header" =~ (@generated|DO[[:space:]]+NOT[[:space:]]+EDIT|AUTO-GENERATED|Code[[:space:]]+generated[[:space:]]+by|AUTOGENERATED|generated[[:space:]]+by[[:space:]]+[a-zA-Z0-9_-]+) ]]; then
        return 0
    fi

    return 1
}

# Collect staged files that are added (A), copied (C), modified (M), or renamed (R)
staged_files=()
while IFS= read -r -d '' file; do
    [ -n "$file" ] && staged_files+=("$file")
done < <(git diff --cached --name-only --diff-filter=ACMR -z)

if [ ${#staged_files[@]} -eq 0 ]; then
    exit 0
fi

violations=()
violation_details=()

for file in "${staged_files[@]}"; do
    if is_ignored_file "$file"; then
        continue
    fi

    # Read byte size directly from git's staged blob index
    bytes=$(git cat-file -s ":$file" 2>/dev/null || echo 0)
    tokens=$(( bytes / BYTES_PER_TOKEN ))

    if [ "$tokens" -gt "$MAX_TOKENS" ]; then
        excess_tokens=$(( tokens - MAX_TOKENS ))
        excess_bytes=$(( bytes - MAX_BYTES ))
        violations+=("$file")
        violation_details+=("  • ${BOLD}${file}${NC}\n    - Size:   ${YELLOW}${bytes} bytes${NC} (~${YELLOW}${tokens} tokens${NC})\n    - Limit:  ${MAX_BYTES} bytes (${MAX_TOKENS} tokens)\n    - Excess: ${RED}+${excess_tokens} tokens${NC} (+${excess_bytes} bytes)")
    fi
done

if [ ${#violations[@]} -gt 0 ]; then
    echo -e ""
    echo -e "${RED}${BOLD}======================================================================${NC}"
    echo -e "${RED}${BOLD} [PRE-COMMIT ERROR] File Token Limit Exceeded (> 5,000 tokens)        ${NC}"
    echo -e "${RED}${BOLD}======================================================================${NC}"
    echo -e "Agent-authored code files must not exceed ${BOLD}5,000 tokens${NC} (~20,000 bytes)."
    echo -e "Calculation rule: ${BOLD}tokens = bytes / 4${NC}."
    echo -e ""
    echo -e "${BOLD}The following ${#violations[@]} staged file(s) violate this limit:${NC}"
    echo -e ""
    for detail in "${violation_details[@]}"; do
        echo -e "$detail"
        echo -e ""
    done
    echo -e "${RED}${BOLD}----------------------------------------------------------------------${NC}"
    echo -e "${BOLD} HOW TO SPLIT THESE FILES (Step-by-Step Instructions)${NC}"
    echo -e "${RED}${BOLD}----------------------------------------------------------------------${NC}"
    echo -e "Large monolithic files impair agent reasoning, exhaust prompt context,"
    echo -e "and violate single-responsibility design. Decompose by domain responsibility:"
    echo -e ""
    echo -e "${BLUE}${BOLD}1. Android / Kotlin Components & Composables:${NC}"
    echo -e "   • Split UI Composables: Extract sub-composables (toolbars, cards,"
    echo -e "     dialogs, list items) from large screens into dedicated files under"
    echo -e "     ${CYAN}ui/components/<Feature>Components.kt${NC}."
    echo -e "   • Separate State & ViewModel: Move UI state definitions and ViewModel"
    echo -e "     logic out of Activity/Composable files into dedicated ${CYAN}<Feature>ViewModel.kt${NC}."
    echo -e "   • Refactor Services & Listeners: Delegate background tasks (e.g., notification"
    echo -e "     parsing, auto-reply dispatching, wake lock/battery optimization) into"
    echo -e "     focused helper or domain use case classes under ${CYAN}util/${NC} or ${CYAN}domain/${NC}."
    echo -e "   • Split Large DAOs & Entities: Instead of a monolithic ${CYAN}Daos.kt${NC}, create"
    echo -e "     discrete interfaces (e.g., ${CYAN}ProductDao.kt${NC}, ${CYAN}ChatLogDao.kt${NC}). Keep each"
    echo -e "     entity class in its own dedicated file under ${CYAN}data/local/entity/${NC}."
    echo -e ""
    echo -e "${BLUE}${BOLD}2. Backend / General Services & Modules:${NC}"
    echo -e "   • Separate Controllers & Logic: Keep endpoint handlers lean; extract"
    echo -e "     business rules into service classes or domain interactors."
    echo -e "   • Separate Models & Schemas: Move DTOs, request/response contracts,"
    echo -e "     and database models into modular schema files."
    echo -e "   • Isolate Data Access: Encapsulate queries and external network clients"
    echo -e "     into dedicated repositories."
    echo -e ""
    echo -e "${BLUE}${BOLD}3. Git Action Workflow to Resolve Now:${NC}"
    echo -e "   1. Unstage the violating file(s):"
    echo -e "      ${YELLOW}git restore --staged <file>${NC}"
    echo -e "   2. Split the file into smaller, focused modules (< 5,000 tokens each)."
    echo -e "   3. Stage the resulting split files:"
    echo -e "      ${YELLOW}git add <new-file-1> <new-file-2> ...${NC}"
    echo -e "   4. Re-run your commit:"
    echo -e "      ${YELLOW}git commit${NC}"
    echo -e ""
    echo -e "${YELLOW}${BOLD}Non-Agent / Generated File Exceptions:${NC}"
    echo -e "   If the file was produced by codegen or a build tool (not an agent):"
    echo -e "   • Add ${BOLD}// @generated${NC} or ${BOLD}/* @generated */${NC} in the first 40 lines, OR"
    echo -e "   • Add the path or glob pattern to ${BOLD}.tokenignore${NC} in the repository root."
    echo -e "${RED}${BOLD}======================================================================${NC}"
    echo -e ""
    exit 1
fi

exit 0
